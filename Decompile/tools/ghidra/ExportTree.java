// Exports a Ghidra program as a browsable decompiled C source tree.
//
// Layout (relative to <outdir>):
//   src/<module>/bank_XXXX.c              250 functions per file, address order
//   build/<module>/meta/bank_XXXX.jsonl   per-function metadata (resume unit)
//   build/<module>/functions.jsonl        merged index
//   build/<module>/symbols.csv            address,size,name,source,decompiled
//   build/<module>/prototypes.h           decompiler-recovered signatures
//   build/<module>/strings.tsv            address, name, string references
//   build/<module>/banks.txt              bank manifest
//
// Resume-safe: an existing bank .c file is not decompiled again.
// Shardable: --shard K/N processes only banks where (bank % N) == K. Run a
// final 0/1 pass afterwards to merge metadata and regenerate the indexes.
//
// Run headless:
//   analyzeHeadless <proj_dir> <proj_name> -process <program> -noanalysis -readOnly \
//     -scriptPath Decompile/tools/ghidra \
//     -postScript ExportTree.java <outdir> <module> [bankSize] [limit] [shardK] [shardN] [codeBlock]
//@category SMR

import java.io.*;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.util.*;

import com.google.gson.*;

import ghidra.app.decompiler.*;
import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.data.StringDataInstance;
import ghidra.program.model.listing.*;
import ghidra.program.model.symbol.Reference;
import ghidra.program.model.symbol.ReferenceManager;

public class ExportTree extends GhidraScript {

    private static final String PRELUDE =
        "/* Generated by Decompile/tools/ghidra/ExportTree.java -- do not edit.\n" +
        " * Reference decompilation of the original machine code. Names starting\n" +
        " * with FUN_/DAT_/LAB_ are Ghidra placeholders, not original symbols. */\n" +
        "#include \"smr_ghidra_types.h\"\n\n";

    private static String esc(String s) {
        StringBuilder b = new StringBuilder();
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            switch (c) {
                case '"': b.append("\\\""); break;
                case '\\': b.append("\\\\"); break;
                case '\n': b.append("\\n"); break;
                case '\r': b.append("\\r"); break;
                case '\t': b.append("\\t"); break;
                default:
                    if (c < 0x20) b.append(String.format("\\u%04x", (int) c));
                    else b.append(c);
            }
        }
        return b.toString();
    }

    private static String csv(String s) {
        return '"' + s.replace("\"", "\"\"") + '"';
    }

    /** First line of a plate comment that begins with "Source: ". */
    private static String sourceOf(Function f) {
        String c = f.getComment();
        if (c == null) return "";
        for (String line : c.split("\n")) {
            if (line.startsWith("Source: ")) return line.substring(8).trim();
        }
        return "";
    }

    /** Best-effort human label from the strings a function references. */
    private List<String> stringsOf(Function f, Listing listing, ReferenceManager refs, int max) {
        Map<Address, String> found = new LinkedHashMap<>();
        InstructionIterator it = listing.getInstructions(f.getBody(), true);
        while (it.hasNext() && found.size() < max * 8) {
            Instruction ins = it.next();
            for (Reference r : refs.getReferencesFrom(ins.getAddress())) {
                Address to = r.getToAddress();
                if (to == null || !currentProgram.getMemory().contains(to)) continue;
                Data d = listing.getDataAt(to);
                if (d == null) continue;
                StringDataInstance s = StringDataInstance.getStringDataInstance(d);
                if (s == StringDataInstance.NULL_INSTANCE) continue;
                String v = s.getStringValue();
                if (v == null) continue;
                v = v.replace("\r", " ").replace("\n", " ").trim();
                if (v.length() < 3 || v.length() > 200) continue;
                found.putIfAbsent(to, v);
            }
        }
        List<String> vals = new ArrayList<>(found.values());
        vals.sort((a, b) -> Integer.compare(score(b), score(a)));
        return vals.size() > max ? vals.subList(0, max) : vals;
    }

    /** Long, wordy strings tend to identify the subsystem. */
    private static int score(String s) {
        int letters = 0, digits = 0;
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (Character.isLetter(c)) letters++;
            else if (Character.isDigit(c)) digits++;
        }
        return Math.min(s.length(), 120) + letters * 2 - digits;
    }

    @Override
    public void run() throws Exception {
        String[] a = getScriptArgs();
        if (a.length < 2) {
            println("usage: ExportTree.java <outdir> <module> [bankSize] [limit] [shardK] [shardN]");
            return;
        }
        File outDir = new File(a[0]);
        String module = a[1];
        int bankSize = a.length > 2 ? Integer.parseInt(a[2]) : 250;
        int limit = a.length > 3 ? Integer.parseInt(a[3]) : 0;
        int shardK = a.length > 4 ? Integer.parseInt(a[4]) : 0;
        int shardN = a.length > 5 ? Integer.parseInt(a[5]) : 1;
        String codeBlock = a.length > 6 ? a[6] : ".text";

        File srcDir = new File(outDir, "src/" + module);
        File buildDir = new File(outDir, "build/" + module);
        File metaDir = new File(buildDir, "meta");
        srcDir.mkdirs();
        metaDir.mkdirs();

        List<Function> funcs = new ArrayList<>();
        int skippedBlocks = 0;
        for (Function f : currentProgram.getFunctionManager().getFunctions(true)) {
            if (f.isExternal()) continue;
            if (!codeBlock.equals("*")) {
                ghidra.program.model.mem.MemoryBlock b =
                    currentProgram.getMemory().getBlock(f.getEntryPoint());
                String bn = b == null ? "" : b.getName();
                if (!bn.equals(codeBlock)) { skippedBlocks++; continue; }
            }
            funcs.add(f);
        }
        println("ExportTree: " + funcs.size() + " functions in " + codeBlock
            + " (" + skippedBlocks + " outside the block skipped)");
        int banks = (funcs.size() + bankSize - 1) / bankSize;
        int firstBank = 0, lastBank = banks;
        if (limit > 0) lastBank = Math.min(banks, (limit + bankSize - 1) / bankSize);

        DecompInterface dec = new DecompInterface();
        dec.setOptions(new DecompileOptions());
        dec.toggleCCode(true);
        dec.setSimplificationStyle("decompile");
        if (!dec.openProgram(currentProgram)) {
            println("ERROR: cannot open decompiler: " + dec.getLastMessage());
            return;
        }

        Listing listing = currentProgram.getListing();
        ReferenceManager refs = currentProgram.getReferenceManager();
        long t0 = System.currentTimeMillis();
        int doneBanks = 0, doneFuncs = 0, failed = 0;

        try (PrintWriter banksOut = new PrintWriter(
                new FileWriter(new File(buildDir, "banks.txt")))) {
            banksOut.println("# bank\tfile\tfirst\tlast\tcount");
            for (int b = firstBank; b < lastBank; b++) {
                if (b % shardN != shardK) continue;
                int from = b * bankSize;
                int to = Math.min(funcs.size(), from + bankSize);
                String bankName = String.format("bank_%04d", b);
                File cFile = new File(srcDir, bankName + ".c");
                File mFile = new File(metaDir, bankName + ".jsonl");
                banksOut.printf("%s\t%s.c\t%s\t%s\t%d%n", bankName, bankName,
                    funcs.get(from).getEntryPoint(), funcs.get(to - 1).getEntryPoint(),
                    to - from);
                if (cFile.isFile() && mFile.isFile() && cFile.length() > 0 && mFile.length() > 0) {
                    continue;
                }

                StringBuilder c = new StringBuilder(PRELUDE);
                StringBuilder meta = new StringBuilder();
                for (int i = from; i < to; i++) {
                    if (monitor.isCancelled()) break;
                    Function f = funcs.get(i);
                    String addr = f.getEntryPoint().toString();
                    String name = f.getName(true);
                    int size = (int) f.getBody().getNumAddresses();
                    String source = sourceOf(f);
                    ghidra.program.model.mem.MemoryBlock mb =
                        currentProgram.getMemory().getBlock(f.getEntryPoint());
                    String region = mb == null ? "" : mb.getName();
                    List<String> calls = new ArrayList<>();
                    try {
                        for (Function callee : f.getCalledFunctions(monitor)) {
                            calls.add(callee.isExternal()
                                ? "ext:" + callee.getName(true)
                                : callee.getEntryPoint().toString());
                        }
                    } catch (Exception ignored) { }
                    List<String> strings = stringsOf(f, listing, refs, 6);

                    DecompileResults r = dec.decompileFunction(f, 120, monitor);
                    boolean ok = r != null && r.decompileCompleted();
                    String text;
                    String sig = "";
                    if (ok) {
                        DecompiledFunction df = r.getDecompiledFunction();
                        text = df.getC();
                        try { sig = df.getSignature(); } catch (Exception ignored) { }
                    } else {
                        text = "/* decompile failed: "
                            + (r == null ? "null" : r.getErrorMessage().replace("*/", "* /"))
                            + " */\n";
                        failed++;
                    }

                    c.append("/* ").append(addr).append("  size ").append(size);
                    if (!source.isEmpty()) c.append("  source: ").append(source);
                    c.append(" */\n");
                    if (!strings.isEmpty()) {
                        c.append("/* strings:");
                        for (String s : strings) c.append(" \"").append(esc(s)).append("\";");
                        c.append(" */\n");
                    }
                    c.append(text).append("\n\n");

                    meta.append("{\"addr\":\"").append(addr)
                        .append("\",\"name\":\"").append(esc(name))
                        .append("\",\"size\":").append(size)
                        .append(",\"bank\":\"").append(bankName)
                        .append("\",\"region\":\"").append(esc(region))
                        .append("\",\"source\":\"").append(esc(source))
                        .append("\",\"decompiled\":").append(ok)
                        .append(",\"signature\":\"").append(esc(sig))
                        .append("\",\"calls\":[");
                    for (int k = 0; k < calls.size(); k++) {
                        if (k > 0) meta.append(',');
                        meta.append('"').append(calls.get(k)).append('"');
                    }
                    meta.append("],\"strings\":[");
                    for (int k = 0; k < strings.size(); k++) {
                        if (k > 0) meta.append(',');
                        meta.append('"').append(esc(strings.get(k))).append('"');
                    }
                    meta.append("]}\n");

                    doneFuncs++;
                    if (doneFuncs % 250 == 0) {
                        long ms = System.currentTimeMillis() - t0;
                        double per = ms / (double) Math.max(1, doneFuncs);
                        println(String.format("ExportTree: %d funcs, %.1f/s, %d failed, eta %.1f min",
                            doneFuncs, 1000.0 / per, failed,
                            (funcs.size() - doneFuncs) * per / 60000.0));
                    }
                }
                writeFile(cFile, c.toString());
                writeFile(mFile, meta.toString());
                banksOut.flush();
                doneBanks++;
            }
        } finally {
            dec.dispose();
        }

        println(String.format("ExportTree[%s]: %d banks, %d functions, %d failed -> %s",
            module, doneBanks, doneFuncs, failed, outDir));
        if (shardK == 0 && shardN == 1) merge(metaDir, buildDir);
    }

    /** Merge per-bank metadata into the stable index files. */
    private void merge(File metaDir, File buildDir) throws IOException {
        File[] metas = metaDir.listFiles((d, n) -> n.endsWith(".jsonl"));
        if (metas == null) return;
        Arrays.sort(metas);

        File functions = new File(buildDir, "functions.jsonl");
        File protos = new File(buildDir, "prototypes.h");
        File syms = new File(buildDir, "symbols.csv");
        File strs = new File(buildDir, "strings.tsv");
        int count = 0, bad = 0;

        try (BufferedWriter wf = new BufferedWriter(new OutputStreamWriter(
                 new FileOutputStream(functions), StandardCharsets.UTF_8));
             PrintWriter wp = new PrintWriter(new OutputStreamWriter(
                 new FileOutputStream(protos), StandardCharsets.UTF_8));
             PrintWriter ws = new PrintWriter(new OutputStreamWriter(
                 new FileOutputStream(syms), StandardCharsets.UTF_8));
             PrintWriter wt = new PrintWriter(new OutputStreamWriter(
                 new FileOutputStream(strs), StandardCharsets.UTF_8))) {

            wp.println("/* Prototypes as recovered by the Ghidra decompiler. */");
            wp.println("#pragma once");
            wp.println("#include \"smr_ghidra_types.h\"\n");
            ws.println("address,size,name,source,decompiled");
            wt.println("# address\tname\tstrings");

            for (File m : metas) {
                for (String line : Files.readAllLines(m.toPath(), StandardCharsets.UTF_8)) {
                    if (line.isBlank()) continue;
                    JsonObject o;
                    try {
                        o = JsonParser.parseString(line).getAsJsonObject();
                    } catch (Exception e) {
                        println("ExportTree: bad metadata line in " + m + ": " + e.getMessage());
                        continue;
                    }
                    wf.write(line);
                    wf.write('\n');
                    count++;
                    String addr = o.get("addr").getAsString();
                    String name = o.get("name").getAsString();
                    String sig = o.has("signature") ? o.get("signature").getAsString() : "";
                    String source = o.has("source") ? o.get("source").getAsString() : "";
                    long size = o.get("size").getAsLong();
                    boolean ok = o.get("decompiled").getAsBoolean();
                    if (!ok) bad++;
                    ws.println(addr + "," + size + "," + csv(name) + "," + csv(source) + "," + ok);
                    if (!sig.isEmpty()) {
                        wp.println(sig.endsWith(";") ? sig : sig + ";");
                    }
                    JsonArray arr = o.has("strings") ? o.getAsJsonArray("strings") : null;
                    if (arr != null && arr.size() > 0) {
                        List<String> vals = new ArrayList<>();
                        for (JsonElement e : arr) vals.add(e.getAsString());
                        wt.println(addr + "\t" + name + "\t"
                            + String.join(" | ", vals).replace("\t", " "));
                    }
                }
            }
        }
        println(String.format("ExportTree: merged %d banks, %d functions (%d failed) -> %s",
            metas.length, count, bad, functions));
    }

    private static String strField(String json, String key) {
        String k = "\"" + key + "\":\"";
        int i = json.indexOf(k);
        if (i < 0) return "";
        i += k.length();
        StringBuilder b = new StringBuilder();
        for (; i < json.length(); i++) {
            char c = json.charAt(i);
            if (c == '\\' && i + 1 < json.length()) {
                char n = json.charAt(++i);
                b.append(n == 'n' ? '\n' : n == 't' ? '\t' : n);
            } else if (c == '"') {
                break;
            } else {
                b.append(c);
            }
        }
        return b.toString();
    }

    private static long intField(String json, String key) {
        String k = "\"" + key + "\":";
        int i = json.indexOf(k);
        if (i < 0) return 0;
        i += k.length();
        int j = i;
        while (j < json.length() && (Character.isDigit(json.charAt(j)) || json.charAt(j) == '-')) j++;
        try { return Long.parseLong(json.substring(i, j)); } catch (Exception e) { return 0; }
    }

    private static void writeFile(File f, String s) throws IOException {
        f.getParentFile().mkdirs();
        try (Writer w = new OutputStreamWriter(new FileOutputStream(f), StandardCharsets.UTF_8)) {
            w.write(s);
        }
    }
}
